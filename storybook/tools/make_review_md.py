def table(slug):
    st = json.load(open(os.path.join(SB, f"story_{slug}.json"), encoding="utf-8"))
    pics = PIC[slug].strip().split("\n")
    assert len(pics) == len(st["pages"]), (slug, len(pics), len(st["pages"]))
    what, hook = ABOUT[slug]
    rows = []
    for p, pic in zip(st["pages"], pics):
        zh = p["zh"]
        if slug == "seesaw":   # 家长要求：「下次用嘴说」改成「下次可以说出来」
            zh = zh.replace("下次用嘴说。", "下次可以说出来。").replace("想玩，用嘴说，不用手。", "想玩，就说出来，不用手。")
        rows.append(f"| {p['n']} | {pic} | {zh.replace(chr(10), ' / ')} |")
    hook_line = f"**在家能用的那句话：** {hook}\n\n" if hook else ""
    return (f"## 《{st['title']}》——{st['subtitle']}（{len(st['pages'])} 页）\n\n"
            f"**这本书在做什么：** {what}\n\n{hook_line}"
            "| 页 | 图里画的是什么 | 现在的旁白（/ 是换行） |\n|---|---|---|\n" + "\n".join(rows) + "\n\n---\n")


